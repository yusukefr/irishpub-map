import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { pathToFileURL } from "node:url";
import { Client } from "@neondatabase/serverless";
import { format } from "prettier";
import { resolveNeonTarget } from "./lib/resolve-neon-target.mjs";

const OUTPUT_PATH = "docs/generated/database-schema.md";

const QUERIES = {
  tables: `
    SELECT table_name
    FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
    ORDER BY table_name
  `,
  columns: `
    SELECT
      table_name,
      column_name,
      data_type,
      udt_name,
      is_nullable,
      column_default,
      character_maximum_length,
      numeric_precision,
      numeric_scale
    FROM information_schema.columns
    WHERE table_schema = 'public'
    ORDER BY table_name, ordinal_position
  `,
  constraints: `
    SELECT
      relation.relname AS table_name,
      con.conname AS constraint_name,
      con.contype AS constraint_type,
      pg_get_constraintdef(con.oid, true) AS definition
    FROM pg_constraint AS con
    JOIN pg_class AS relation ON relation.oid = con.conrelid
    JOIN pg_namespace AS namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = 'public'
    ORDER BY relation.relname, con.conname
  `,
  indexes: `
    SELECT tablename AS table_name, indexname AS index_name, indexdef AS definition
    FROM pg_indexes
    WHERE schemaname = 'public'
    ORDER BY tablename, indexname
  `,
};

const CONSTRAINT_TYPES = { c: "CHECK", f: "FOREIGN KEY", p: "PRIMARY KEY", u: "UNIQUE" };

/** Postgresカタログの行から、手動編集しない安定したスキーマMarkdownを生成します。 */
export function formatDatabaseSchema({ tables, columns, constraints, indexes }) {
  const sortedTables = [...tables].sort((left, right) => left.table_name.localeCompare(right.table_name));
  const sections = [
    "# Database schema (generated)",
    "",
    "> **Do not edit this file manually.** Run `npm run db:schema -- --target production` to regenerate it from the Production Neon PostgreSQL schema.",
    "> The generator performs read-only catalog queries and never writes the connection string or table data.",
    "",
    "This document records the physical schema in PostgreSQL `public`: tables, columns, constraints (including foreign keys), and indexes.",
  ];

  for (const table of sortedTables) {
    const tableName = table.table_name;
    sections.push(
      "",
      `## ${tableName}`,
      "",
      "### Columns",
      "",
      "| Column | Type | Nullable | Default |",
      "| --- | --- | --- | --- |",
    );
    const tableColumns = columns.filter((column) => column.table_name === tableName);
    for (const column of tableColumns) {
      sections.push(
        `| \`${column.column_name}\` | ${formatType(column)} | ${column.is_nullable === "YES" ? "yes" : "no"} | ${formatValue(column.column_default)} |`,
      );
    }
    if (tableColumns.length === 0) sections.push("| _No columns found_ |  |  |  |");

    sections.push("", "### Constraints", "", "| Name | Type | Definition |", "| --- | --- | --- |");
    const tableConstraints = constraints
      .filter((constraint) => constraint.table_name === tableName)
      .sort((left, right) => left.constraint_name.localeCompare(right.constraint_name));
    for (const constraint of tableConstraints) {
      sections.push(
        `| \`${constraint.constraint_name}\` | ${CONSTRAINT_TYPES[constraint.constraint_type] ?? constraint.constraint_type} | ${formatValue(constraint.definition)} |`,
      );
    }
    if (tableConstraints.length === 0) sections.push("| _No constraints found_ |  |  |");

    sections.push("", "### Indexes", "", "| Name | Definition |", "| --- | --- |");
    const tableIndexes = indexes
      .filter((index) => index.table_name === tableName)
      .sort((left, right) => left.index_name.localeCompare(right.index_name));
    for (const index of tableIndexes) sections.push(`| \`${index.index_name}\` | ${formatValue(index.definition)} |`);
    if (tableIndexes.length === 0) sections.push("| _No indexes found_ |  |");
  }

  return `${sections.join("\n")}\n`;
}

/** 接続先のPostgresカタログをread-onlyで読み、生成用のスキーマ情報を返します。 */
export async function readDatabaseSchema(databaseUrl, sql) {
  if (!databaseUrl) throw new Error("DATABASE_URL is required.");
  if (sql) {
    const [tables, columns, constraints, indexes] = await Promise.all([
      sql(QUERIES.tables),
      sql(QUERIES.columns),
      sql(QUERIES.constraints),
      sql(QUERIES.indexes),
    ]);
    return { tables, columns, constraints, indexes };
  }

  const client = new Client(databaseUrl);
  await client.connect();
  try {
    const [tables, columns, constraints, indexes] = await Promise.all([
      client.query(QUERIES.tables),
      client.query(QUERIES.columns),
      client.query(QUERIES.constraints),
      client.query(QUERIES.indexes),
    ]);
    return { tables: tables.rows, columns: columns.rows, constraints: constraints.rows, indexes: indexes.rows };
  } finally {
    await client.end();
  }
}

/** `--check`指定時に生成物が最新かを検査し、それ以外は標準出力へ生成内容を返します。 */
export async function run(databaseUrl, args, { readSchema = readDatabaseSchema, readOutput = readFile } = {}) {
  if (args.length > 1 || (args[0] && args[0] !== "--check"))
    throw new Error("Usage: node scripts/generate-database-schema.mjs [--check]");
  const output = await format(formatDatabaseSchema(await readSchema(databaseUrl)), { filepath: OUTPUT_PATH });
  if (args[0] !== "--check") return output;

  let existing;
  try {
    existing = await readOutput(OUTPUT_PATH, "utf8");
  } catch {
    throw new Error(`${OUTPUT_PATH} is missing. Run npm run db:schema -- --target production.`);
  }
  if (existing !== output)
    throw new Error(`${OUTPUT_PATH} is out of date. Run npm run db:schema -- --target production.`);
  return "";
}

function formatType(column) {
  if (column.data_type === "USER-DEFINED") return `\`${column.udt_name}\``;
  if (column.data_type === "character varying" && column.character_maximum_length)
    return `\`varchar(${column.character_maximum_length})\``;
  if (column.data_type === "numeric" && column.numeric_precision)
    return `\`numeric(${column.numeric_precision}${column.numeric_scale === null ? "" : `,${column.numeric_scale}`})\``;
  return `\`${column.data_type}\``;
}

function formatValue(value) {
  if (!value) return "—";

  const normalized = String(value).replace(/\s+/g, " ").trim().replaceAll("|", "\\|");

  return "`" + normalized + "`";
}

async function main() {
  try {
    const args = [...process.argv.slice(2)];
    let target;
    const targetIndex = args.indexOf("--target");
    if (targetIndex !== -1) {
      target = args[targetIndex + 1];
      args.splice(targetIndex, 2);
    }
    if (target !== "production") throw new Error("Database schema generation requires --target production.");
    if (args.length > 1 || (args[0] && args[0] !== "--check"))
      throw new Error("Usage: npm run db:schema -- --target production [--check]");

    const resolvedTarget = await resolveNeonTarget(target);
    const output = await run(resolvedTarget.connectionString, args);
    if (output) {
      await mkdir(dirname(OUTPUT_PATH), { recursive: true });
      await writeFile(OUTPUT_PATH, output);
      console.log("Generated " + OUTPUT_PATH + ".");
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : "Could not generate database schema.";
    console.error(
      message.startsWith("Usage:") || message.includes(OUTPUT_PATH) || message.includes("requires --target")
        ? message
        : "Could not generate database schema from Neon.",
    );
    process.exitCode = 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
